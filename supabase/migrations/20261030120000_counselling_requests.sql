-- ===========================================================================
-- Counselling requests — the student-facing form (GMI-RO-P04-F02) and the
-- counsellor registry that decides who may read it.
--
-- Access model
-- ------------
--   anon           No policies and no grants. A student's browser key cannot
--                  read, insert or update anything here. Submissions arrive
--                  only through the `submit-counselling-request` edge
--                  function, which holds the service-role key in its own
--                  environment and never ships it to a browser.
--   authenticated  Readable and updatable only by an *active* counsellor.
--                  Accounts are invite-only: public sign-up must stay
--                  disabled in Authentication → Providers.
--   service_role   Bypasses RLS, which is what the edge function needs.
--
-- Everything a student types is frozen at insert time. Counsellors may only
-- change the "For Office Use Only" columns — see
-- counselling_requests_freeze_submission() at the bottom of this file.
-- ===========================================================================

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- 1. Counsellor registry
--
-- One row per invited counsellor, carrying the display fields the dashboard
-- sidebar and top bar already expect from js/data.js getProfile().
-- ---------------------------------------------------------------------------

create table public.counsellor_profiles (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  full_name  text not null check (length(btrim(full_name)) between 2 and 120),
  role       text not null default 'Counsellor',
  department text not null default 'Student Counselling Unit',
  initials   text,
  avatar_url text,
  email      text,
  active     boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.counsellor_profiles is
  'Invited counsellors. A row with active = true is what makes an authenticated user a counsellor.';

-- ---------------------------------------------------------------------------
-- 2. Reference code
--
-- Students quote this when they follow up, so it is short and readable
-- rather than a UUID. Generated by the database, never by the client.
-- ---------------------------------------------------------------------------

create sequence public.counselling_request_seq;

create or replace function public.next_counselling_reference()
returns text
language sql
volatile
set search_path = ''
as $$
  select 'CR-' || to_char(now(), 'YYYY') || '-' ||
         lpad(nextval('public.counselling_request_seq')::text, 4, '0');
$$;

-- ---------------------------------------------------------------------------
-- 3. Requests
--
-- Purposes and issues are arrays rather than join tables. The dashboard
-- already exports these lists as constants and renders them as chips, so a
-- lookup table would buy nothing that the CHECK constraint below does not
-- already guarantee. Swap to join tables if either list ever needs to carry
-- its own metadata.
-- ---------------------------------------------------------------------------

create table public.counselling_requests (
  id             uuid primary key default gen_random_uuid(),
  reference_code text not null unique default public.next_counselling_reference(),

  -- Section A of the paper form. `channel` is forced to 'Online' by the edge
  -- function; the other values exist so a counsellor can log a walk-in,
  -- telephone or letter request from the dashboard.
  request_type text not null check (request_type in ('Request', 'Referral')),
  channel      text not null default 'Online'
               check (channel in ('Online', 'Walk In', 'Telephone', 'Email', 'Letter/Memo')),

  -- Section B — student background.
  student_name text not null check (length(btrim(student_name)) between 2 and 120),
  student_id   text not null check (length(btrim(student_id)) between 3 and 32),
  semester     text not null check (length(btrim(semester)) between 1 and 32),
  contact_no   text not null check (length(btrim(contact_no)) between 7 and 32),
  email        text not null check (email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[a-z]{2,}$'),

  -- Section C — purposes. At least one, all drawn from the printed list.
  purposes      text[] not null check (
                  cardinality(purposes) between 1 and 5
                  and purposes <@ array[
                    'Individual Counselling', 'Group Counselling', 'Guidance',
                    'Psychometric Test', 'Other'
                  ]::text[]
                ),
  purpose_other text check (purpose_other is null or length(btrim(purpose_other)) between 2 and 120),

  -- Section D — types of issue.
  issues      text[] not null check (
                cardinality(issues) between 1 and 8
                and issues <@ array[
                  'Academic', 'Health', 'Personal', 'Career',
                  'Relationship', 'Further Study', 'Finance', 'Other'
                ]::text[]
              ),
  issue_other text check (issue_other is null or length(btrim(issue_other)) between 2 and 120),

  description text not null check (length(btrim(description)) between 20 and 4000),

  -- "For Office Use Only". Never accepted from the student form: the edge
  -- function drops these keys if a payload carries them.
  status                 text not null default 'New'
                         check (status in ('New', 'Under Review', 'Completed')),
  reference_source       text check (
                           reference_source is null
                           or reference_source in ('HOD/HOS', 'TTO/Lecturer', 'Friends', 'Family Member')
                         ),
  appointment_at         timestamptz,
  assigned_counsellor_id uuid references auth.users (id) on delete set null,
  office_notes           text check (office_notes is null or length(office_notes) <= 4000),

  submitted_at timestamptz not null default now(),
  updated_at   timestamptz not null default now(),

  -- "Other" means nothing without the short text beside it, and the text
  -- means nothing unless "Other" is ticked. Enforced here as well as in the
  -- edge function, so a direct service-role insert cannot skip it either.
  constraint purpose_other_matches_selection
    check (('Other' = any (purposes)) = (purpose_other is not null)),
  constraint issue_other_matches_selection
    check (('Other' = any (issues)) = (issue_other is not null))
);

comment on table public.counselling_requests is
  'Student counselling requests and referrals. Student-supplied columns are immutable after insert.';

create index counselling_requests_submitted_at_idx
  on public.counselling_requests (submitted_at desc);
create index counselling_requests_status_idx
  on public.counselling_requests (status);
create index counselling_requests_student_id_idx
  on public.counselling_requests (student_id);

-- ---------------------------------------------------------------------------
-- 4. Abuse control for the public endpoint
--
-- Counted per salted IP hash per hour. No raw address is stored. Only the
-- service-role edge function reaches this table, through the function below.
-- ---------------------------------------------------------------------------

create table public.submission_throttle (
  ip_hash      text        not null,
  window_start timestamptz not null,
  count        integer     not null default 1,
  primary key (ip_hash, window_start)
);

create or replace function public.register_submission_attempt(
  p_ip_hash text,
  p_limit   integer default 5
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_window timestamptz := date_trunc('hour', now());
  v_count  integer;
begin
  insert into public.submission_throttle as t (ip_hash, window_start, count)
  values (p_ip_hash, v_window, 1)
  on conflict (ip_hash, window_start)
    do update set count = t.count + 1
  returning t.count into v_count;

  -- Opportunistic cleanup; this table should never grow past a day of traffic.
  delete from public.submission_throttle where window_start < now() - interval '2 hours';

  return v_count <= p_limit;
end;
$$;

-- ---------------------------------------------------------------------------
-- 5. Who counts as a counsellor
--
-- SECURITY DEFINER so that the policies on counsellor_profiles can call it
-- without re-entering their own RLS check.
-- ---------------------------------------------------------------------------

create or replace function public.is_counsellor()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.counsellor_profiles p
    where p.user_id = (select auth.uid())
      and p.active
  );
$$;

-- ---------------------------------------------------------------------------
-- 6. Triggers
-- ---------------------------------------------------------------------------

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger counselling_requests_touch
  before update on public.counselling_requests
  for each row execute function public.touch_updated_at();

create trigger counsellor_profiles_touch
  before update on public.counsellor_profiles
  for each row execute function public.touch_updated_at();

-- A submitted request is a record of what a student wrote. Counsellors work
-- the office-use columns; they do not get to rewrite the student's words.
create or replace function public.counselling_requests_freeze_submission()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if row (
       new.reference_code, new.request_type, new.channel, new.student_name,
       new.student_id, new.semester, new.contact_no, new.email,
       new.purposes, new.purpose_other, new.issues, new.issue_other,
       new.description, new.submitted_at
     ) is distinct from row (
       old.reference_code, old.request_type, old.channel, old.student_name,
       old.student_id, old.semester, old.contact_no, old.email,
       old.purposes, old.purpose_other, old.issues, old.issue_other,
       old.description, old.submitted_at
     )
  then
    raise exception
      'A submitted counselling request cannot be edited. Only the office-use fields may change.'
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

create trigger counselling_requests_freeze
  before update on public.counselling_requests
  for each row execute function public.counselling_requests_freeze_submission();

-- Accounts are created by invitation in the Supabase dashboard. Giving each
-- new user a profile row here is what admits them to the queue, so there is
-- no second manual step to forget.
create or replace function public.handle_new_counsellor()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name text := coalesce(
    nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''),
    initcap(replace(split_part(new.email, '@', 1), '.', ' '))
  );
begin
  insert into public.counsellor_profiles (user_id, full_name, email, initials)
  values (
    new.id,
    v_name,
    new.email,
    upper(left(split_part(v_name, ' ', 1), 1) || coalesce(left(nullif(split_part(v_name, ' ', 2), ''), 1), ''))
  )
  on conflict (user_id) do nothing;
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_counsellor();

-- ---------------------------------------------------------------------------
-- 7. Grants
--
-- Supabase grants the API roles broad privileges on new public tables by
-- default, so anon's access is revoked explicitly rather than assumed away.
-- ---------------------------------------------------------------------------

revoke all on public.counselling_requests  from anon;
revoke all on public.counsellor_profiles   from anon;
revoke all on public.submission_throttle   from anon, authenticated;
revoke all on sequence public.counselling_request_seq from anon, authenticated;

grant select, insert, update on public.counselling_requests to authenticated;
grant select, update          on public.counsellor_profiles  to authenticated;

revoke all on function public.register_submission_attempt(text, integer) from public, anon, authenticated;
revoke all on function public.next_counselling_reference() from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 8. Row level security
-- ---------------------------------------------------------------------------

alter table public.counselling_requests  enable row level security;
alter table public.counselling_requests  force  row level security;
alter table public.counsellor_profiles   enable row level security;
alter table public.counsellor_profiles   force  row level security;

-- Enabled with no policy at all: only the service-role function touches it.
alter table public.submission_throttle   enable row level security;
alter table public.submission_throttle   force  row level security;

create policy "Counsellors read requests"
  on public.counselling_requests for select to authenticated
  using ((select public.is_counsellor()));

create policy "Counsellors update requests"
  on public.counselling_requests for update to authenticated
  using ((select public.is_counsellor()))
  with check ((select public.is_counsellor()));

-- Lets a counsellor log a walk-in or telephone request from the dashboard.
create policy "Counsellors log offline requests"
  on public.counselling_requests for insert to authenticated
  with check ((select public.is_counsellor()));

-- No delete policy, deliberately: nothing removes a request through the API.

create policy "Counsellors read the roster"
  on public.counsellor_profiles for select to authenticated
  using ((select public.is_counsellor()));

create policy "Counsellors update their own profile"
  on public.counsellor_profiles for update to authenticated
  using  (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

-- ---------------------------------------------------------------------------
-- 9. Realtime
--
-- Realtime applies the SELECT policy above per subscriber, so only an active
-- counsellor's socket receives a row. Replica identity is left at the primary
-- key: the dashboard re-runs its query on any event rather than reading the
-- payload, so no old column values need to go over the wire.
-- ---------------------------------------------------------------------------

alter publication supabase_realtime add table public.counselling_requests;
